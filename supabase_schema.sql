create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  role text not null default 'customer'
    check (role in ('customer', 'analyzer')),
  created_at timestamptz not null default now()
);

create table if not exists public.tickets (
  id bigint generated by default as identity primary key,
  customer_id uuid not null references public.profiles(id) on delete cascade,
  customer_name text not null,
  customer_email text not null,
  subject varchar(200) not null,
  description text not null,
  category varchar(50) not null default 'Uncategorized',
  priority varchar(20) not null default 'Medium'
    check (priority in ('Low', 'Medium', 'High', 'Urgent')),
  status varchar(30) not null default 'Open'
    check (status in ('Open', 'In Progress', 'Resolved')),
  sentiment varchar(30) not null default 'Unknown',
  ai_suggested_reply text,
  analyzer_reply text,
  analyzer_reply_at timestamptz,
  customer_reply_seen_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.tickets
  add column if not exists analyzer_reply text,
  add column if not exists analyzer_reply_at timestamptz,
  add column if not exists customer_reply_seen_at timestamptz;

create index if not exists tickets_customer_created_idx
  on public.tickets (customer_id, created_at desc);
create index if not exists tickets_queue_created_idx
  on public.tickets (created_at desc);

create or replace function public.create_customer_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    'customer'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create or replace function public.protect_customer_ticket_updates()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if exists (
    select 1 from public.profiles
    where profiles.id = (select auth.uid())
      and profiles.role = 'customer'
  ) then
    new.customer_id := old.customer_id;
    new.id := old.id;
    new.customer_name := old.customer_name;
    new.customer_email := old.customer_email;
    new.category := old.category;
    new.priority := old.priority;
    new.status := old.status;
    new.sentiment := old.sentiment;
    new.ai_suggested_reply := old.ai_suggested_reply;
    new.analyzer_reply := old.analyzer_reply;
    new.analyzer_reply_at := old.analyzer_reply_at;
    new.created_at := old.created_at;
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_supportdesk on auth.users;
create trigger on_auth_user_created_supportdesk
  after insert on auth.users
  for each row execute function public.create_customer_profile();

drop trigger if exists protect_customer_ticket_updates on public.tickets;
create trigger protect_customer_ticket_updates
  before update on public.tickets
  for each row execute function public.protect_customer_ticket_updates();

alter table public.profiles enable row level security;
alter table public.tickets enable row level security;

revoke all on public.profiles from anon, authenticated;
grant select on public.profiles to authenticated;

revoke all on public.tickets from anon, authenticated;
grant select, insert, update on public.tickets to authenticated;
grant usage, select on sequence public.tickets_id_seq to authenticated;

drop policy if exists "Users can read their own profile" on public.profiles;
create policy "Users can read their own profile"
  on public.profiles for select to authenticated
  using (id = (select auth.uid()));

drop policy if exists "Customers can read their own tickets" on public.tickets;
create policy "Customers can read their own tickets"
  on public.tickets for select to authenticated
  using (
    customer_id = (select auth.uid())
    or exists (
      select 1 from public.profiles
      where profiles.id = (select auth.uid())
        and profiles.role = 'analyzer'
    )
  );

drop policy if exists "Customers can create their own tickets" on public.tickets;
create policy "Customers can create their own tickets"
  on public.tickets for insert to authenticated
  with check (
    customer_id = (select auth.uid())
    and exists (
      select 1 from public.profiles
      where profiles.id = (select auth.uid())
        and profiles.role = 'customer'
    )
  );

drop policy if exists "Analyzers can update tickets" on public.tickets;
drop policy if exists "Customers can edit their open tickets" on public.tickets;
drop policy if exists "Customers and analyzers can update permitted tickets" on public.tickets;
create policy "Customers and analyzers can update permitted tickets"
  on public.tickets for update to authenticated
  using (
    (
      customer_id = (select auth.uid())
      and status <> 'Resolved'
      and exists (
        select 1 from public.profiles
        where profiles.id = (select auth.uid())
          and profiles.role = 'customer'
      )
    )
    or exists (
      select 1 from public.profiles
      where profiles.id = (select auth.uid())
        and profiles.role = 'analyzer'
    )
  )
  with check (
    (
      customer_id = (select auth.uid())
      and exists (
        select 1 from public.profiles
        where profiles.id = (select auth.uid())
          and profiles.role = 'customer'
      )
    )
    or exists (
      select 1 from public.profiles
      where profiles.id = (select auth.uid())
        and profiles.role = 'analyzer'
    )
  );

notify pgrst, 'reload schema';
